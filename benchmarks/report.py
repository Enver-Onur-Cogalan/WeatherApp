#!/usr/bin/env python3
"""
Turn benchmark result files into a markdown table.

The harness writes one JSON file per (model, thinking-mode) run. This collects them
into the comparison table that goes in the README, so the published numbers are
generated from measurements rather than typed by hand.

Usage:
    python3 report.py                 # print to stdout
    python3 report.py --write         # write results/COMPARISON.md
"""

import argparse
import json
from pathlib import Path

HERE = Path(__file__).parent
RESULTS = HERE / "results"

ROWS = [
    ("Correct tool selected", "tool_correct_rate", "pct"),
    ("Called any tool", "tool_call_rate", "pct"),
    ("Schema valid", "schema_valid_rate", "pct"),
    ("Plausible hour values", "schema_sane_hours_rate", "pct"),
    ("Tool calls with schema on", "constrained_call_rate", "pct"),
    ("Constraint tax", "constraint_tax", "delta"),
    ("Answered Turkish in Turkish", "turkish_rate", "pct"),
    ("Median latency", "median_tool_latency", "secs"),
]


def load_runs():
    runs = []
    for path in sorted(RESULTS.glob("*.json")):
        if path.name == "engine-schema-enforcement.json":
            continue
        data = json.loads(path.read_text())
        if "summary" not in data:
            continue
        engine = "MLX" if "-mlx" in data["model"] else "GGUF"
        mode = "thinking" if data.get("think") else "no-thinking"
        runs.append(
            {
                "label": f"{data['model']}<br><sub>{engine} · {mode}</sub>",
                "summary": data["summary"],
                "repeat": data["repeat"],
            }
        )
    return runs


def fmt(value, kind):
    if kind == "pct":
        return f"{value:.0%}"
    if kind == "delta":
        return f"{value:+.0%}"
    return f"{value:.1f}s"


def render(runs):
    if not runs:
        return "_No benchmark results yet. Run `python3 run.py <model>` first._\n"

    lines = [
        "# Benchmark comparison",
        "",
        "Generated by `report.py` from the files in `results/`. "
        f"Each figure is a rate over {runs[0]['repeat']} repeats per case, temperature 0.",
        "",
        "| Measurement | " + " | ".join(r["label"] for r in runs) + " |",
        "|---|" + "---|" * len(runs),
    ]
    for label, key, kind in ROWS:
        cells = [fmt(r["summary"].get(key, 0), kind) for r in runs]
        lines.append(f"| {label} | " + " | ".join(cells) + " |")

    lines += [
        "",
        "## Reading this table",
        "",
        "- **Correct tool selected** counts the *first* tool call only. A right answer",
        "  after a wrong one is a miss, because an agent loop would already have acted.",
        "- **Constraint tax** is the drop in tool-calling when a schema is applied in the",
        "  same request. A negative number supports",
        "  [ADR-0006](../docs/adr/ADR-0006-two-phase-tool-and-schema.md); a flat zero on an",
        "  engine that ignores `format` means the test measured nothing — see",
        "  [ADR-0011](../docs/adr/ADR-0011-gguf-engine-over-mlx.md).",
        "- **Schema valid** is meaningless on the MLX engine, which drops the constraint",
        "  silently. It is reported anyway, because that zero is the evidence.",
        "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()

    output = render(load_runs())
    if args.write:
        out = RESULTS / "COMPARISON.md"
        out.write_text(output)
        print(f"written to {out.relative_to(HERE.parent)}")
    else:
        print(output)


if __name__ == "__main__":
    main()
